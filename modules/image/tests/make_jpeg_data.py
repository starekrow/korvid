# Writes jpeg_data.h: small JPEGs of each kind jpeg.cc decodes, made by Pillow (on
# libjpeg-turbo), and Pillow's decodes of them as RGB, the reference jpeg_test.cc compares
# against. Run from this directory with Pillow installed:  python3 make_jpeg_data.py
import io
import random
from PIL import Image, ImageOps

W, H = 45, 33  # odd, and not a whole number of MCUs either way


def picture(mode="RGB"):
    """A small 'photograph': gradients, a ring, a sharp edge, and noise."""
    rnd = random.Random(25)
    img = Image.new("RGB", (W, H))
    px = img.load()
    for y in range(H):
        for x in range(W):
            r = (x * 255) // (W - 1)
            g = (y * 255) // (H - 1)
            d = (x - 20) ** 2 + (y - 15) ** 2
            b = 230 if 60 < d < 160 else 40
            if x > 33 and y < 10:
                r, g, b = 250, 250, 20
            n = rnd.randint(-12, 12)
            px[x, y] = (max(0, min(255, r + n)), max(0, min(255, g - n)), max(0, min(255, b + n)))
    return img.convert(mode) if mode != "RGB" else img


def save(img, **kw):
    out = io.BytesIO()
    img.save(out, "JPEG", **kw)
    return out.getvalue()


def rgb_of(data, scale=1, transpose=False):
    im = Image.open(io.BytesIO(data))
    if scale > 1:
        im.draft(im.mode, (im.size[0] // scale, im.size[1] // scale))  # draft takes the largest scale that still gives this
    if transpose:
        im = ImageOps.exif_transpose(im)
    im = im.convert("RGB")
    return im.size, im.tobytes()


exif6 = Image.Exif()
exif6[0x0112] = 6
cases = [
    ("b444", save(picture(), quality=90, subsampling=0)),
    ("b422", save(picture(), quality=90, subsampling=1)),
    ("b420", save(picture(), quality=90, subsampling=2)),
    ("gray", save(picture("L"), quality=90)),
    ("p420", save(picture(), quality=90, subsampling=2, progressive=True)),
    ("p444", save(picture(), quality=85, subsampling=0, progressive=True)),
    ("pgray", save(picture("L"), quality=90, progressive=True)),
    ("rst", save(picture(), quality=90, subsampling=2, restart_marker_blocks=3)),
    ("cmyk", save(picture("CMYK"), quality=90)),
    ("exif6", save(picture(), quality=90, subsampling=2, exif=exif6.tobytes())),
]

lines = ["// Generated by make_jpeg_data.py: JPEGs Pillow made (on libjpeg-turbo), and its decodes of",
         "// them as RGB: at full size, at the scales asked, and turned by EXIF where they say so.",
         "#pragma once", ""]


def arr(name, data):
    lines.append("static const unsigned char %s[%d] = {%s};" % (name, len(data), ",".join(str(b) for b in data)))


for name, data in cases:
    arr("k_jpeg_%s" % name, data)
    (w, h), rgb = rgb_of(data, transpose=(name == "exif6"))
    lines.append("static const unsigned k_jpeg_%s_w = %d, k_jpeg_%s_h = %d;" % (name, w, name, h))
    arr("k_jpeg_%s_rgb" % name, rgb)
    if name in ("b444", "b420", "p420", "gray"):
        for s in (2, 4, 8):
            (w, h), rgb = rgb_of(data, scale=s)
            lines.append("static const unsigned k_jpeg_%s_%d_w = %d, k_jpeg_%s_%d_h = %d;" % (name, s, w, name, s, h))
            arr("k_jpeg_%s_%d_rgb" % (name, s), rgb)
    lines.append("")

with open("jpeg_data.h", "w") as f:
    f.write("\n".join(lines))
print("wrote jpeg_data.h:", sum(len(l) for l in lines), "bytes")
