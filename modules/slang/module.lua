-- The shader compiler as a module: it provides "shader-compile" and exports the rule
-- that turns a .slang file into what the platform's renderer loads, with every module's
-- shaders/ directory on the include path (a game's shader includes the render interface's
-- sprite_fragment.slangh by name). A system lookup for now; a vendored binary would be
-- prebuilt = { linux = "bin/linux/slangc" } in this directory.
--
-- SPIR-V for Vulkan by default. On the Apple family a Metal library: Slang drives Xcode's Metal compiler
-- itself (the Metal Toolchain component must be installed), defines KV_TARGET_METAL for the
-- render interface's Metal-only declarations, and writes its reflection beside the library
-- (<out>.json: every parameter's binding by name), which a dev build of renderer-metal checks
-- its layouts against. docs/design/renderer-metal.md has why.
module "slang" {
  output   = "exe",
  provides = "shader-compile",
  system   = "slangc",
  exports  = {
    rule "shader" {
      inputs  = "shaders/*.slang",
      outputs = "%{stem}.spv",
      command = "%{tool} %{in} %{shader_includes} -target spirv -fvk-use-entrypoint-name -depfile %{depfile} -o %{out}",
      deps    = "depfile",
      platforms = {
        -- The Apple family (toolchain.apple's family): Metal's compiler builds for the
        -- consuming platform's triple (air64-apple-ios26.0-simulator), since a library is
        -- built for one OS and an iOS Metal refuses a macOS library. It compiles Slang's
        -- generated MSL, not our source, so its warnings are about Slang's code: temporaries
        -- holding an atomic's unused result, and every StructuredBuffer declared writable
        -- (device*, never const), which a vertex function that returns a value is warned
        -- for, with no flag to name. -w quiets that stage; Slang's own diagnostics on the
        -- source (implicit conversions, type errors) come before it and still show.
        apple = {
          outputs = "%{stem}.metallib",
          command = "%{tool} %{in} %{shader_includes} -target metallib -DKV_TARGET_METAL=1 -Xmetal -target -Xmetal air64-%{triple} -Xmetal -w " ..
                    "-depfile %{depfile} -reflection-json %{out}.json -o %{out}",
        },
        -- Wherever renderer-d3d12 is bound: DXIL, which holds one entry point per blob where
        -- SPIR-V and a Metal library hold many. A .zip output is slangc's container, one
        -- signed blob per entry point (DXC signs it; no dxil.dll), which the backend reads
        -- by entry name. KV_TARGET_D3D12 turns on the render interface's registers
        -- (binding.slangh) and its vertex fetch of the sorted rows. Shader model 6.0: what
        -- every D3D12 GPU runs, the oldest Xbox and the ARM laptops included.
        ["renderer-d3d12"] = {
          outputs = "%{stem}.dxil.zip",
          command = "%{tool} %{in} %{shader_includes} -target dxil -profile sm_6_0 -DKV_TARGET_D3D12=1 " ..
                    "-depfile %{depfile} -o %{out}",
        },
      },
    },
    -- Wherever renderer-cpu is bound: each game shader as C++ for the CPU renderer, inside
    -- the engine's span kernel (renderer-cpu's shaders/cpu_*.slangh, the post one for a
    -- shader that includes post_fragment.slangh), compiled into the game and registered by
    -- a generated engine module (korvid/renderer-cpu/shader_glue.inl has why it is shaped so).
    rule "shader_cpu" {
      inputs  = "shaders/*.slang",
      outputs = "%{stem}.cpu.cpp",
      bound   = "renderer-cpu",
      command = "%{tool} %{in} %{shader_includes} -target cpp -entry cs_span -stage compute -depfile %{depfile} -o %{out}",
      deps    = "depfile",
      wrap    = {
        { match = "post_fragment.slangh", text = '#include "cpu_begin.slangh"\n#include "%{in}"\n#include "cpu_post.slangh"\n' },
        { text = '#include "cpu_begin.slangh"\n#include "%{in}"\n#include "cpu_sprite.slangh"\n' },
      },
      glue = [[
// generated by kormake: %{stem} for the CPU renderer (slang's shader_cpu rule)
#include "korvid/renderer-cpu/shader_glue.h"
#define cs_span cs_span_%{symbol}
#define cs_span_Group cs_span_Group_%{symbol}
#define cs_span_Thread cs_span_Thread_%{symbol}
namespace kv_cpu_%{symbol} {
#include "%{out}"
#include "korvid/renderer-cpu/shader_glue.inl"
}
KV_CPU_SHADER_MODULE(%{symbol}_cpu, "%{stem}", kv_cpu_%{symbol}::kv_cpu_entry)
]],
      engine_module = "%{symbol}_cpu_module",
    },
  },
}
