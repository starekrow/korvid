def split(x, bits):
    # The leading `bits` significant bits of x (truncated), as an exact double.
    x = F(x)
    e = 0
    while abs(x) >= 2 ** (bits - 1) * F(2) ** e: e += 1
    while abs(x) < 2 ** (bits - 1) * F(2) ** e: e -= 1
    q = int(x / F(2) ** e)
    return F(q) * F(2) ** e

