def atan_series(z):
    # atan(z) = z - z^3/3 + ...; z is halved twice first so the series converges fast.
    for _ in range(3):
        z = z / (1 + (1 + z * z).sqrt())
    s, term, n, z2 = D(0), z, 0, z * z
    while True:
        t = term / (2 * n + 1)
        if abs(t) < D(10) ** -440: break
        s += t if n % 2 == 0 else -t
        term *= z2
        n += 1
    return s * 8

