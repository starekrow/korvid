#!/usr/bin/env python3
# Writes modules/math/src/constants.h: the constants the scalar functions are built
# from, each a correctly rounded double (or exact bits) computed here at 450 digits with
# Python's decimal, so nothing depends on the machine that ran it. Run it from anywhere;
# the output is committed, and running it again must reproduce it byte for byte.
import os
from decimal import Decimal as D, getcontext
from fractions import Fraction as F
from math import factorial

getcontext().prec = 450

def atan_series(z):
    # atan(z) = z - z^3/3 + ...; z is halved twice first so the series converges fast.
    for _ in range(3):
        z = z / (1 + (1 + z * z).sqrt())
    s, term, n, z2 = D(0), z, 0, z * z
    while True:
        t = term / (2 * n + 1)
        if abs(t) < D(10) ** -440: break
        s += t if n % 2 == 0 else -t
        term *= z2
        n += 1
    return s * 8

PI = 16 * atan_series(D(1) / 5) - 4 * atan_series(D(1) / 239)
LN2 = D(2).ln()
LN10 = D(10).ln()

def frac(d):  # a Decimal as an exact Fraction
    return F(d)

def rd(x):  # nearest double, as a hex literal
    return float(F(x)).hex()

def split(x, bits):
    # The leading `bits` significant bits of x (truncated), as an exact double.
    x = F(x)
    e = 0
    while abs(x) >= 2 ** (bits - 1) * F(2) ** e: e += 1
    while abs(x) < 2 ** (bits - 1) * F(2) ** e: e -= 1
    q = int(x / F(2) ** e)
    return F(q) * F(2) ** e

out = []
w = out.append
w("// generated by modules/math/check/gen_constants.py; do not edit")
w("#pragma once")
w('#include "korvid/core/types.h"')
w("")
w("namespace kv::math_constants {")
pio2 = frac(PI) / 2
p1 = split(pio2, 33); p2 = split(pio2 - p1, 33); p3 = pio2 - p1 - p2
w("// pi/2 in three parts: the first two of 33 bits, so k * part is exact for |k| < 2^20.")
w(f"inline constexpr f64 kPio2_1 = {float(p1).hex()};")
w(f"inline constexpr f64 kPio2_2 = {float(p2).hex()};")
w(f"inline constexpr f64 kPio2_3 = {rd(p3)};")
w(f"inline constexpr f64 kPio2 = {rd(pio2)};")
w(f"inline constexpr f64 kPio2Lo = {rd(pio2 - F(float(pio2)))};")
w(f"inline constexpr f64 kPi = {rd(frac(PI))};")
w(f"inline constexpr f64 kPiLo = {rd(frac(PI) - F(float(frac(PI))))};")
w(f"inline constexpr f64 kPio4 = {rd(frac(PI) / 4)};")
w(f"inline constexpr f64 k3Pio4 = {rd(3 * frac(PI) / 4)};")
w(f"inline constexpr f64 kInvPio2 = {rd(2 / frac(PI))};")
ln2 = frac(LN2)
l1 = split(ln2, 42)
w("// ln 2 in two parts: the first of 42 bits, so k * part is exact for |k| < 2^11.")
w(f"inline constexpr f64 kLn2_1 = {float(l1).hex()};")
w(f"inline constexpr f64 kLn2_2 = {rd(ln2 - l1)};")
w(f"inline constexpr f64 kLn2 = {rd(ln2)};")
w(f"inline constexpr f64 kLn2Lo = {rd(ln2 - F(float(ln2)))};")
w(f"inline constexpr f64 kInvLn2 = {rd(1 / ln2)};")
w(f"inline constexpr f64 kInvLn2Lo = {rd(1 / ln2 - F(float(1 / ln2)))};")
w(f"inline constexpr f64 kTwoThirds = {rd(F(2, 3))};")
w(f"inline constexpr f64 kTwoThirdsLo = {rd(F(2, 3) - F(float(F(2, 3))))};")
w(f"inline constexpr f64 kInvLn10 = {rd(1 / frac(LN10))};")
w(f"inline constexpr f64 kLog10_2 = {rd(ln2 / frac(LN10))};")
w("// 1/n!, n = 0..17: the exp and sin/cos series.")
w("inline constexpr f64 kInvFact[18] = {")
for n in range(18): w(f"    {rd(F(1, factorial(n)))},")
w("};")
w("// 1/(2n+1), n = 0..12: the atan and log series.")
w("inline constexpr f64 kInvOdd[13] = {")
for n in range(13): w(f"    {rd(F(1, 2 * n + 1))},")
w("};")
w("// atan(k/8), k = 0..8, as a double and what it leaves out.")
w("inline constexpr f64 kAtanHi[9] = {")
hi = []
for k in range(9):
    v = frac(atan_series(D(k) / 8)) if k else F(0)
    hi.append(v)
    w(f"    {rd(v)},")
w("};")
w("inline constexpr f64 kAtanLo[9] = {")
for v in hi: w(f"    {rd(v - F(float(v)))},")
w("};")
# 2/pi's fractional bits, most significant first: bit 1 is the first bit after the point.
# 1280 bits reach past what the largest double needs (bit 970 plus a 160-bit window).
tp = 2 / frac(PI)
words = []
t = tp - int(tp)
for _ in range(41):
    t *= 2 ** 32
    words.append(int(t))
    t -= int(t)
w("// 2/pi's fractional bits, 32 to a word, most significant first (Payne-Hanek).")
w("inline constexpr u32 kTwoOverPi[41] = {")
for i in range(0, 41, 6): w("    " + " ".join(f"0x{x:08x}u," for x in words[i:i + 6]))
w("};")
w("} // namespace kv::math_constants")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "constants.h")
open(path, "w").write("\n".join(out) + "\n")
print(path)
