/* kormake: embeds the Lua scripts into the binary. Usage: embed out.inc file... ; each
 * file becomes an entry {name, text} in kormake_scripts[], the name being the basename
 * without its extension. */
#include <stdio.h>
#include <string.h>

int main(int argc, char** argv) {
    if (argc < 3) { fprintf(stderr, "usage: embed out.inc script.lua...\n"); return 2; }
    FILE* out = fopen(argv[1], "w");
    if (!out) { perror(argv[1]); return 1; }
    fprintf(out, "/* generated by embed.c; do not edit */\n");
    fprintf(out, "static const struct { const char* name; const char* text; } kormake_scripts[] = {\n");
    for (int i = 2; i < argc; ++i) {
        FILE* in = fopen(argv[i], "rb");
        if (!in) { perror(argv[i]); return 1; }
        const char* base = strrchr(argv[i], '/');
        base = base ? base + 1 : argv[i];
        char name[128];
        snprintf(name, sizeof name, "%s", base);
        char* dot = strrchr(name, '.');
        if (dot) *dot = 0;
        fprintf(out, "  {\"%s\",\n  \"", name);
        int c, col = 0;
        while ((c = fgetc(in)) != EOF) {
            if (c == '\\' || c == '"') { fputc('\\', out); fputc(c, out); col += 2; }
            else if (c == '\n') { fputs("\\n\"\n  \"", out); col = 0; }
            else if (c < 32 || c > 126) { fprintf(out, "\\%03o", c); col += 4; }
            else { fputc(c, out); ++col; }
        }
        fprintf(out, "\"},\n");
        fclose(in);
    }
    fprintf(out, "  {0, 0}\n};\n");
    fclose(out);
    return 0;
}
